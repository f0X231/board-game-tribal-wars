/**
 * research:cgt-subgame
 * After J. Song & M. Müller (2012), "An Enhanced Solver for the Game of Amazons".
 *
 * Board partitioning: the empty squares are split into 8-connected regions.
 *  - Simple Territory  — touched by one tribe only, none of its totems also
 *                        borders a contested area;
 *  - Blocker Territory — touched by one tribe, but a bordering totem (a
 *                        Blocker) also borders an Active Area, so that totem
 *                        must choose where to spend its turns;
 *  - Active Area       — touched by two or more tribes (still contested).
 * Each territory gets lower/upper bounds on the turns it is worth: the lower
 * bound comes from plodding filling (king steps + arrows burned on dead ends),
 * the upper bound from its size (a Tribal Wars turn burns two squares).
 * A territory whose lower bound is below its upper bound is Defective (dead ends).
 *
 * Safe moves (AES = adjacent empty squares): territory moves are generated by
 * rules 1–6 — (1) step into a dead end first, (2) burn squares that are already
 * isolated, (3) keep an exit for the totem, (4) never burn a region articulation,
 * (5) prefer corridors (AES = 2), (6) verify the plodding bound drops by at most
 * one turn. These moves are "tempo" options inside the active-area search.
 *
 * Search: iterative-deepening alpha-beta over Active-Area moves (+ one safe
 * territory move per own territory) with a transposition table; the evaluation
 * is the sum of subgame bounds plus the tempo rule (equal turns → the side to
 * move runs out first). With no Active Area left, a proof-oriented single-agent
 * search plays the territories out.
 */
import { AlphaBeta } from './search.js';
import { type BotMove, type BotTurnInput, type ResearchBot, runPlacement } from './common.js';
import {
  type FastBoard,
  type Region,
  INF,
  Scratch,
  actionName,
  arrowValue,
  bestFillAction,
  eliminationTerm,
  features,
  fillUpperBound,
  opponentMask,
  pack,
  plodFill,
  popcount,
  queenDistance,
  regions,
  signed,
  statLine,
  twoStage,
} from './evalUtils.js';

export interface Partition {
  regions: Region[];
  active: Region[];
  /** Exclusive regions per slot. */
  territories: Region[][];
  /** Piece cells that border both an own territory and an active area. */
  blockers: Set<number>;
}

export function partition(fb: FastBoard, s: Scratch): Partition {
  const rs = regions(fb, s);
  const active = rs.filter((r) => popcount(r.tribes) >= 2);
  const territories: Region[][] = [[], [], [], []];
  const bordersActive = new Set<number>();
  for (const r of active) for (const p of r.pieces) bordersActive.add(p.cell);
  const blockers = new Set<number>();
  for (const r of rs) {
    if (popcount(r.tribes) !== 1) continue;
    const slot = Math.log2(r.tribes);
    territories[slot]!.push(r);
    for (const p of r.pieces) if (bordersActive.has(p.cell)) blockers.add(p.cell);
  }
  return { regions: rs, active, territories, blockers };
}

/** Lower / upper turn bounds of a territory (plodding for small regions, defect estimate for big ones). */
export function territoryBounds(fb: FastBoard, slot: number, r: Region): { lower: number; upper: number } {
  const upper = fillUpperBound(r);
  const lower = r.cells.length <= 14 ? Math.min(upper, plodFill(fb, slot, r)) : Math.max(0, Math.floor((r.cells.length - r.deadEnds) / 2));
  return { lower, upper };
}

/** Subgame-sum evaluation (root perspective, in turns). */
function subgameEval(fb: FastBoard, root: number, toMove: number, s: Scratch): number {
  const part = partition(fb, s);
  const turns = [0, 0, 0, 0];
  for (let slot = 0; slot < 4; slot++) {
    for (const r of part.territories[slot]!) {
      const { lower, upper } = territoryBounds(fb, slot, r);
      const v = 0.7 * lower + 0.3 * upper;
      // A blocker can only spend its turns in one place: discount shared territories.
      turns[slot]! += r.pieces.some((p) => part.blockers.has(p.cell)) ? 0.8 * v : v;
    }
  }
  if (part.active.length > 0) {
    // Active areas: split by Queen-distance ownership (root vs. union of opponents).
    queenDistance(fb, 1 << root, s.q1me, s.queue);
    queenDistance(fb, opponentMask(fb, root), s.q1op, s.queue);
    let mine = 0;
    let theirs = 0;
    for (const r of part.active) {
      for (const c of r.cells) {
        const a = s.q1me[c]!;
        const b = s.q1op[c]!;
        if (a < b) mine++;
        else if (b < a) theirs++;
        else if (a !== INF) {
          mine += 0.5;
          theirs += 0.5;
        }
      }
    }
    turns[root]! += mine / 2;
    const opps = fb.opponents(root);
    for (const o of opps) turns[o]! += theirs / 2 / Math.max(1, opps.length);
  }
  const opps = fb.opponents(root);
  let oppTurns = 0;
  for (const o of opps) oppTurns += turns[o]!;
  oppTurns /= Math.max(1, opps.length);
  // Tempo rule: with equal turns left, the side to move runs out first.
  const tempo = toMove === root ? -0.5 : 0.5;
  return turns[root]! - oppTurns + tempo;
}

/** Safe territory move by AES rules 1–6 (see header); -1 if none qualifies. */
export function safeTerritoryMove(fb: FastBoard, slot: number, r: Region): number {
  const inRegion = new Uint8Array(fb.size);
  for (const c of r.cells) inRegion[c] = 1;
  const cands: Array<{ a: number; score: number }> = [];
  for (const p of r.pieces) {
    if (p.slot !== slot) continue;
    const from = p.cell;
    const dests: number[] = [];
    fb.rays(from, dests, 0);
    for (const to of dests) {
      if (!inRegion[to]) continue;
      const k = fb.move(slot, from, to);
      const arrows: number[] = [];
      fb.rays(to, arrows, 0);
      const aesTo = fb.emptyNeighbours(to);
      for (const sh of arrows) {
        const aesSh = fb.emptyNeighbours(sh);
        let score = 0;
        if (aesTo <= 1) score += 6; // R1: dead-end destination first
        if (aesSh === 0) score += 8; // R2: square already isolated: burning it costs nothing
        const adjacent = isAdjacent(fb, to, sh);
        if (aesTo - (adjacent ? 1 : 0) < 1) score -= 10; // R3: keep an exit
        if (aesSh >= 3) score -= 3 * (aesSh - 2); // R4: avoid burning articulations
        if (aesTo === 2) score += 2; // R5: corridors
        score -= 0.25 * aesSh;
        cands.push({ a: pack(from, to, sh), score });
      }
      fb.unmove(slot, from, to, k);
    }
  }
  if (cands.length === 0) return -1;
  cands.sort((x, y) => y.score - x.score);
  // R6: proof check on the best few — plodding bound may drop by at most one turn.
  const before = plodFill(fb, slot, r);
  for (const { a } of cands.slice(0, 4)) {
    const k = fb.make(slot, a);
    const after = regions(fb, new Scratch(fb.size))
      .filter((x) => x.tribes === 1 << slot && x.cells.some((c) => inRegion[c]))
      .reduce((sum, x) => sum + plodFill(fb, slot, x), 0);
    fb.unmake(slot, a, k);
    if (after >= before - 1) return a;
  }
  return cands[0]!.a;
}

function isAdjacent(fb: FastBoard, a: number, b: number): boolean {
  return Math.max(Math.abs(fb.g.row[a]! - fb.g.row[b]!), Math.abs(fb.g.col[a]! - fb.g.col[b]!)) === 1;
}

export function createCgtSubgame(): ResearchBot {
  return {
    id: 'research:cgt-subgame',
    label: 'CGT Subgame Solver',
    paper: 'Song & Müller 2012',
    description: 'Board partition (simple/blocker territories, active areas), plodding bounds, AES safe moves, iterative alpha-beta over active areas.',

    place(input) {
      const s = new Scratch(input.fb.size);
      return runPlacement(
        input,
        (fb, p) => {
          const f = features(fb, p, s, 0, true);
          // King-move territory + regional potential; spread totems so none becomes a lone blocker.
          let crowd = 0;
          const list = fb.pieces[p]!;
          for (let i = 0; i < list.length; i++)
            for (let j = i + 1; j < list.length; j++) if (isAdjacent(fb, list[i]!, list[j]!)) crowd++;
          return f.t2 + 0.5 * f.c2 + 0.2 * f.t1 - 3 * crowd;
        },
        'Subgame draft: stake out king-distance regions that can become separate territories.',
      );
    },

    play(input: BotTurnInput): BotMove {
      const { fb, me, clock } = input;
      const s = new Scratch(fb.size);
      const part = partition(fb, s);
      const myBounds = part.territories[me]!.map((r) => territoryBounds(fb, me, r));
      const lo = myBounds.reduce((x, b) => x + b.lower, 0);
      const hi = myBounds.reduce((x, b) => x + b.upper, 0);
      const defective = myBounds.filter((b) => b.lower < b.upper).length;
      const summary = `${part.active.length} active area(s), ${part.territories[me]!.length} territory(ies) worth ${lo}–${hi} turns${defective ? `, ${defective} defective` : ''}, ${part.blockers.size} blocker(s)`;

      if (part.active.every((r) => !(r.tribes & (1 << me)))) {
        const fill = bestFillAction(fb, me, clock);
        return {
          action: fill.action,
          reasoning:
            `No contested area left for us — proof-oriented territory filling: ${actionName(fb, fill.action)}. ` +
            statLine([['Fill', `${fill.turns} turns${fill.proven ? ' (optimal)' : ''}`], ['nodes', fill.nodes], ['', summary]]),
        };
      }

      const cs = new Scratch(fb.size);
      const es = new Scratch(fb.size);
      const dMe = new Uint8Array(fb.size);
      const dOp = new Uint8Array(fb.size);
      const gen = (b: FastBoard, slot: number, keep: number) => {
        const pt = partition(b, cs);
        const activeIds = new Set(pt.active.map((r) => r.id));
        const comp = cs.comp;
        const list = twoStage(
          b,
          slot,
          {
            filter: (_from, to) => activeIds.has(comp[to]!),
            moveScore: (bb, sl) => {
              const f = features(bb, sl, es, 0, false);
              return f.t1 + 0.05 * (f.mobMe - f.mobOpp);
            },
            prepareArrows: (bb, sl) => {
              queenDistance(bb, 1 << sl, dMe, es.queue);
              queenDistance(bb, opponentMask(bb, sl), dOp, es.queue);
            },
            arrowScore: (bb, sl, _to, sh) => arrowValue(bb, sl, sh, dMe, dOp),
            moveKeep: 10,
            arrowsPerMove: 4,
            keep,
          },
          clock,
        );
        // One safe tempo move per own territory (CGT: playing in a territory is a "switch").
        for (const r of pt.territories[slot]!.slice(0, 2)) {
          const a = safeTerritoryMove(b, slot, r);
          if (a >= 0 && !list.includes(a)) list.push(a);
        }
        if (list.length === 0) return twoStage(b, slot, { moveScore: (bb) => bb.empties, arrowScore: () => 0, moveKeep: 6, arrowsPerMove: 2, keep: 4 }, clock);
        return list;
      };
      const ab = new AlphaBeta(
        fb,
        {
          evaluate: (b, rt, toMove) => subgameEval(b, rt, toMove, s) + eliminationTerm(b, rt, 20),
          candidates: (b, slot) => gen(b, slot, 12),
          rootCandidates: (b, slot) => gen(b, slot, 18),
        },
        { maxDepth: 32, tt: true, aspiration: null, pvs: false, killers: false, epsilon: 0.01 },
      );
      const r = ab.run(me, clock);
      return {
        action: r.action,
        reasoning:
          `Subgame α-β over active areas: ${actionName(fb, r.action)}. ` +
          statLine([['Depth', r.depth], ['', `${r.nodes.toLocaleString('en-US')} nodes`], ['Score', `${signed(r.score)} turns`], ['TT hits', r.ttHits], ['', summary]]),
      };
    },
  };
}

